function getSubjectUnits(subject: string): Unit[] {
  if (subject.includes("语文")) return units;
  if (subject.includes("数学")) return mathUnits;
  if (subject.includes("英") || subject.includes("外语")) return englishUnits;
  if (subject.includes("物理")) return physicsUnits;
  if (subject.includes("历史")) return historyUnits;
  return [];
}

export function getSubjectConfig(subject?: string): SubjectConfig {
  const subjectName = subject || "初中语文";
  const mockUnits = getSubjectUnits(subjectName);
  const allKnowledgePoints = mockUnits.flatMap((u) => u.knowledgePoints);
  const avgMastery =
    allKnowledgePoints.length > 0
      ? Math.round(
          allKnowledgePoints.reduce((s, k) => s + k.mastery, 0) /
            allKnowledgePoints.length,
        )
      : 0;
  return {
    subject: subjectName,
    semester: "七年级下册",
    edition: "部编版（2017）",
    unitCount: mockUnits.length,
    knowledgeCount: allKnowledgePoints.length,
    avgMastery,
    units: mockUnits,
    // 评分标准 / 能力模型 / 教材关联 为纯演示数据且无持久化路径，不再 mock 冒充，返回空态
    scoring: [],
    abilities: [],
    textbooks: [],
  };
}
