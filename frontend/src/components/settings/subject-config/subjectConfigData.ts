// ── Subject Configuration Mock Data ──

export interface KnowledgePoint {
  id: string;
  code: string;
  name: string;
  unitId: string;
  level: "识记" | "理解" | "应用" | "评价";
  mastery: number; // 0-100
  isWeak: boolean;
  prerequisite: string[];
  postrequisite: string[];
  related: string[];
  hours: number;
  keyPoint: string;
  difficulty: string;
  commonErrors: string;
  resources: { type: string; name: string }[];
}

export interface Unit {
  id: string;
  index: number;
  name: string;
  subtitle: string;
  knowledgePoints: KnowledgePoint[];
}

export interface ScoringDimension {
  id: string;
  name: string;
  maxScore: number;
  levels: { label: string; range: string; description: string }[];
}

export interface AbilityDimension {
  id: string;
  name: string;
  description: string;
  classAvg: number; // 1-5
  target: number;
}

export interface TextbookMapping {
  unitName: string;
  lessonName: string;
  standards: string[];
  knowledgeIds: string[];
  abilities: string[];
  literacy: string;
}

export interface SubjectConfig {
  subject: string;
  semester: string;
  edition: string;
  unitCount: number;
  knowledgeCount: number;
  avgMastery: number;
  units: Unit[];
  scoring: ScoringDimension[];
  abilities: AbilityDimension[];
  textbooks: TextbookMapping[];
}

