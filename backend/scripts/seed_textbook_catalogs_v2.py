def seed():
    _ensure_textbook_catalogs_table()
    total_top = 0
    total_unit = 0
    with engine.begin() as conn:
        # 清空旧目录（纯参考表，无外键）
        conn.execute(text("DELETE FROM textbook_catalogs"))
        for edition, subjects in DATA.items():
            for subject, grades in subjects.items():
                for grade, books in grades.items():
                    for book in books:
                        top_id = gen_uuid()
                        conn.execute(
                            text(
                                "INSERT INTO textbook_catalogs "
                                "(id, name, subject, edition, grade, level, unit_index, parent_id) "
                                "VALUES (:id, :n, :s, :e, :g, 'edition', NULL, NULL)"
                            ),
                            {"id": top_id, "n": book["book"], "s": subject,
                             "e": edition, "g": grade},
                        )
                        total_top += 1
                        for idx, name in enumerate(book["units"], 1):
                            conn.execute(
                                text(
                                    "INSERT INTO textbook_catalogs "
                                    "(id, name, subject, edition, grade, level, unit_index, parent_id) "
                                    "VALUES (:id, :n, :s, :e, :g, 'unit', :idx, :p)"
                                ),
                                {"id": gen_uuid(), "n": name, "s": subject,
                                 "e": edition, "g": grade, "idx": idx, "p": top_id},
                            )
                            total_unit += 1

    print(f"seed v2 完成：共写入 {total_top} 个分册顶层节点、{total_unit} 个单元节点")
    with engine.connect() as conn:
        rows = conn.execute(
            text(
                "SELECT edition, COUNT(DISTINCT grade) AS grades, "
                "COUNT(*) AS nodes FROM textbook_catalogs GROUP BY edition ORDER BY edition"
            )
        ).fetchall()
        for edition, grades, nodes in rows:
            print(f"  {edition}: {grades} 个年级, {nodes} 行")


if __name__ == "__main__":
    seed()
